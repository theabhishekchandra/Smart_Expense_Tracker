package com.abhishek.smartexpensetracker.ui.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

// Shared spacing scale so padding/gaps are chosen from one set of values instead of screens
// each picking their own arbitrary dp numbers.
object AppSpacing {
    val xs: Dp = 4.dp
    val sm: Dp = 8.dp
    val md: Dp = 16.dp
    val lg: Dp = 24.dp
    val xl: Dp = 32.dp
    val xxl: Dp = 48.dp
}
